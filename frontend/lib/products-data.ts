// Load products from localStorage on the client (dev convenience). Falls back to defaults on server.
function loadProductsFromStorage() {
  if (typeof window === "undefined") return DEFAULT_PRODUCTS;
  try {
    const raw = window.localStorage.getItem("selit_products");
    if (!raw) return DEFAULT_PRODUCTS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    return DEFAULT_PRODUCTS;
  } catch (e) {
    console.error("Failed to parse stored products:", e);
    return DEFAULT_PRODUCTS;
  }
}

export const PRODUCTS = loadProductsFromStorage();

export function persistProducts() {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem("selit_products", JSON.stringify(PRODUCTS));
  } catch (e) {
    console.error("Failed to persist products:", e);
  }
}
