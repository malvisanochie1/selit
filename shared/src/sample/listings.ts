function toListing(seed: Seed): Listing {
  const { daysAgo, sellerId, status = 'active', ...rest } = seed;
  const createdAt = new Date(
    NOW - daysAgo * 86_400_000 - 3_600_000 * (seed.viewsCount % 9),
  ).toISOString();
  return {
    ...rest,
    sellerId,
    status,
    imagePaths: [],
    reviewReason: status === 'pending' ? 'New seller' : null,
    createdAt,
    updatedAt: createdAt,
    seller: sellerSummary(sellerId),
  };
}

export const SAMPLE_LISTINGS: Listing[] = SEEDS.map(toListing);
